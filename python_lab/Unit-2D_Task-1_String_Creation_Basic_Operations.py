# String creation
str1 = "Hello"
str2 = "World"

print("First String:", str1)
print("Second String:", str2)

# String concatenation
result = str1 + " " + str2
print("Concatenation:", result)

# String repetition
print("Repetition:", str1 * 3)

# String slicing
print("Slicing:", result[0:5])
print("First character:", result[0])
print("Last character:", result[-1])
