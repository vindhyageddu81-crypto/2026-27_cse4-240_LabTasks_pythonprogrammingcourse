# String methods demonstration

str1 = "  Hello Python Programming  "

# upper()
print("Uppercase:", str1.upper())

# lower()
print("Lowercase:", str1.lower())

# strip()
print("Strip:", str1.strip())

# split()
words = str1.split()
print("Split:", words)

# join()
print("Join:", "-".join(words))

# replace()
print("Replace:", str1.replace("Python", "Java"))

# find()
print("Find:", str1.find("Python"))
