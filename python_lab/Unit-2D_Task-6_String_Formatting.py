# String formatting demonstration

name = "Vindhya"
age = 18
course = "Python"

# Using format()
print("Using format():")
print("My name is {} and my age is {}".format(name, age))

# Using f-strings
print("\nUsing f-strings:")
print(f"My name is {name} and I am learning {course}")

# Using % operator
print("\nUsing % operator:")
print("My name is %s and my age is %d" % (name, age))
